DROP TABLE WMUSER.WM_FTP_CONNECTIONS CASCADE CONSTRAINTS;

CREATE TABLE WMUSER.WM_FTP_CONNECTIONS
(
  FTP_CONN_ID     VARCHAR2(50 BYTE)             NOT NULL,
  FTP_SERVERHOST  VARCHAR2(100 BYTE)            NOT NULL,
  FTP_SERVERPORT  NUMBER(5)                     DEFAULT 22                    NOT NULL,
  FTP_USERNAME    VARCHAR2(50 BYTE)             NOT NULL,
  FTP_PASSWORD    VARCHAR2(255 BYTE)            NOT NULL,
  FTP_BASE_DIR    VARCHAR2(255 BYTE)            NOT NULL,
  DESCRIPTION     VARCHAR2(255 BYTE),
  PROTOCOL        VARCHAR2(10 BYTE)             DEFAULT 'SFTP',
  ACTIVE          CHAR(1 BYTE)                  DEFAULT 'Y'                   NOT NULL,
  CREATED_BY      VARCHAR2(50 BYTE)             DEFAULT USER,
  CREATED_DATE    TIMESTAMP(6)                  DEFAULT CURRENT_TIMESTAMP,
  MODIFIED_BY     VARCHAR2(50 BYTE),
  MODIFIED_DATE   TIMESTAMP(6)
)
TABLESPACE SATELITES
PCTFREE    10
INITRANS   1
MAXTRANS   255
STORAGE    (
            INITIAL          64K
            NEXT             1M
            MINEXTENTS       1
            MAXEXTENTS       UNLIMITED
            PCTINCREASE      0
            BUFFER_POOL      DEFAULT
           )
LOGGING 
NOCOMPRESS 
NOCACHE;

COMMENT ON TABLE WMUSER.WM_FTP_CONNECTIONS IS 'Parámetros dinámicos de conexión SFTP/FTP para consumo desde webMethods';

COMMENT ON COLUMN WMUSER.WM_FTP_CONNECTIONS.FTP_CONN_ID IS 'ID o alias de conexión utilizado en los Flow Services (ej. PR50POS)';

COMMENT ON COLUMN WMUSER.WM_FTP_CONNECTIONS.FTP_PASSWORD IS 'Contraseña cifrada mediante WM_ENCRYPTION';

COMMENT ON COLUMN WMUSER.WM_FTP_CONNECTIONS.FTP_BASE_DIR IS 'Ruta raíz del buzón de tienda';


CREATE UNIQUE INDEX WMUSER.PK_WM_FTP_CONNECTIONS ON WMUSER.WM_FTP_CONNECTIONS
(FTP_CONN_ID)
LOGGING
TABLESPACE SATELITES
PCTFREE    10
INITRANS   2
MAXTRANS   255
STORAGE    (
            INITIAL          64K
            NEXT             1M
            MINEXTENTS       1
            MAXEXTENTS       UNLIMITED
            PCTINCREASE      0
            BUFFER_POOL      DEFAULT
           );

ALTER TABLE WMUSER.WM_FTP_CONNECTIONS ADD (
  CONSTRAINT CHK_WM_FTP_ACTIVE
  CHECK (ACTIVE IN ('Y', 'N'))
  ENABLE VALIDATE
,  CONSTRAINT PK_WM_FTP_CONNECTIONS
  PRIMARY KEY
  (FTP_CONN_ID)
  USING INDEX WMUSER.PK_WM_FTP_CONNECTIONS
  ENABLE VALIDATE);
